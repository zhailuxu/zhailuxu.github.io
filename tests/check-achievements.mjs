import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const root=new URL('../',import.meta.url);
const source=fs.readFileSync(new URL('hpx-achievements.js',root),'utf8');
const page=fs.readFileSync(new URL('achievements.html',root),'utf8');
const daily=fs.readFileSync(new URL('daily-camp.html',root),'utf8');
const paradise=fs.readFileSync(new URL('game-paradise.html',root),'utf8');
const roadmap=fs.readFileSync(new URL('ROADMAP.md',root),'utf8');
const sources=fs.readFileSync(new URL('CONTENT_SOURCES.md',root),'utf8');
const store=new Map();
const localStorage={getItem:key=>store.get(key)||null,setItem:(key,value)=>store.set(key,value),removeItem:key=>store.delete(key)};
const context={globalThis:{localStorage},Date};
vm.runInContext(source,vm.createContext(context),{filename:'hpx-achievements.js'});
const api=context.globalThis.HpxAchievements;
assert.ok(api,'成就API没有初始化');
assert.equal(api.BADGES.length,10,'第一版徽章数量不是10枚');
const progress={games:{a:{visits:2,completed:3,hints:0,bestStreak:3},b:{visits:1,completed:0,hints:0,bestStreak:0},c:{visits:1,completed:0,hints:0,bestStreak:0},d:{visits:1,completed:0,hints:0,bestStreak:0},e:{visits:1,completed:0,hints:0,bestStreak:0}},events:[{gameId:'a',type:'mistake',at:100},{gameId:'a',type:'complete',at:200}]};
const dailyState={plans:{'2026-08-18':{completedAt:1},'2026-08-19':{completedAt:2},'2026-08-20':{completedAt:3}}};
const result=api.evaluate(progress,dailyState,new Date(2026,7,20,12).getTime());
const ids=Array.from(result.newlyUnlocked,badge=>badge.id);
['first-finish','three-finishes','explore-five','steady-three','independent-three','try-again','camp-three'].forEach(id=>assert.ok(ids.includes(id),'符合条件但未解锁：'+id));
assert.equal(api.evaluate(progress,dailyState,new Date(2026,7,20,13).getTime()).newlyUnlocked.length,0,'已解锁徽章被重复提示');
assert.equal(api.dailyStreak(dailyState,new Date(2026,7,20,12).getTime()),3,'连续训练天数计算错误');
assert.equal(api.recovered(progress.events),true,'误选后完成没有识别为进步');
assert.ok(page.includes('已获得 0 / 10'),'成就页缺少解锁汇总');
assert.ok(page.includes('不设置积分排行'),'成就页缺少无排名说明');
assert.ok(daily.includes('id="newBadges"'),'每日训练完成页缺少新徽章提示');
assert.ok(paradise.includes('href="achievements.html"'),'游戏乐园缺少我的成就入口');
assert.ok(roadmap.includes('**成就徽章系统（第一版）**'),'路线图没有标记成就功能完成');
assert.ok(sources.includes('`hpx-achievements.js` / `achievements.html` 成就徽章'),'内容来源没有登记成就功能');
console.log('成就徽章检查通过：解锁条件、去重、连续训练、重试进步、页面入口和本地隐私完整。');
